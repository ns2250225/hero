export const ICON_FALLBACK = ICONS.star;

export function getIcon(glyph: string): IconDef {
  return ICONS[glyph] ?? ICON_FALLBACK;
}

const cache = new Map<string, string>();

/** 生成 data URL，供 Vue 的 <img> 使用 */
export function iconDataUrl(glyph: string, size = 48, tint?: string): string {
  const key = `${glyph}|${size}|${tint ?? ''}`;
  const hit = cache.get(key);
  if (hit) return hit;
  const def = getIcon(glyph);
  const main = tint ?? def.color;
  const dark = shade(main, -0.45);
  const cvs = document.createElement('canvas');
  cvs.width = size;
  cvs.height = size;
  const ctx = cvs.getContext('2d')!;
  const s = size / ICON_SIZE;
  for (let y = 0; y < ICON_SIZE; y++) {
    const row = def.rows[y] ?? '';
    for (let x = 0; x < row.length; x++) {
      const ch = row[x];
      if (ch === '.') continue;
      ctx.fillStyle = ch === '+' ? dark : ch === 'o' ? lighten(main, 0.45) : main;
      ctx.fillRect(Math.floor(x * s), Math.floor(y * s), Math.ceil(s), Math.ceil(s));
    }
  }
  const url = cvs.toDataURL();
  cache.set(key, url);
  return url;
}

/** 渲染成 Phaser 可用的字符矩阵 + 调色板 */
export function iconPixelData(glyph: string, tint?: string): { pixels: string[]; palette: Record<string, string> } {
  const def = getIcon(glyph);
  const main = tint ?? def.color;
  return {
    pixels: def.rows,
    palette: { '#': main, '+': shade(main, -0.45), o: lighten(main, 0.45) },
  };
}

export function lighten(hex: string, amount: number): string {
  const c = hexToRgb(hex);
  const r = Math.round(c[0] + (255 - c[0]) * amount);
  const g = Math.round(c[1] + (255 - c[1]) * amount);
  const b = Math.round(c[2] + (255 - c[2]) * amount);
  return rgbToHex(r, g, b);
}

export function shade(hex: string, amount: number): string {
  const c = hexToRgb(hex);
  const f = 1 + amount;
  return rgbToHex(Math.round(c[0] * f), Math.round(c[1] * f), Math.round(c[2] * f));
}

export function hexToRgb(hex: string): [number, number, number] {
  let h = hex.replace('#', '');
  if (h.length === 3) h = h.split('').map((c) => c + c).join('');
  const n = parseInt(h, 16);
  return [(n >> 16) & 255, (n >> 8) & 255, n & 255];
}

export function rgbToHex(r: number, g: number, b: number): string {
  const cl = (v: number) => Math.max(0, Math.min(255, v));
  return `#${((1 << 24) + (cl(r) << 16) + (cl(g) << 8) + cl(b)).toString(16).slice(1)}`;
}

export function hexToNumber(hex: string): number {
  return parseInt(hex.replace('#', ''), 16);
}
