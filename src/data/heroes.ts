function stats(s: Partial<HeroStats>): HeroStats {
  const base: HeroStats = {
    maxHp: 150,
    hp: 150,
    attack: 12,
    defense: 3,
    attackSpeed: 1,
    attackRange: 520,
    critRate: 0.05,
    critDamage: 1.5,
    dodgeRate: 0.03,
    cooldownReduction: 0,
    skillPower: 1,
    lifeSteal: 0,
    blockCapacity: 0,
  };
  const r = { ...base, ...s };
  r.hp = r.maxHp;
  return r;
}

